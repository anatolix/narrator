from collections import defaultdict
def load(fn):
    d=defaultdict(set)
    for ln in open(fn,encoding='utf-8'):
        ln=ln.split('#')[0].strip().lstrip('_')
        if not ln: continue
        m=re.match(r'^([^(]*)\(([^)]*)\)(.*)$',ln)
        forms=[m.group(1)+e+m.group(3) for e in m.group(2).split('|')] if m else [ln]
        for f in forms:
            f=f.lower()
            if 'ё' in f: d[f.replace('ё','е')].add(f)
    return d
