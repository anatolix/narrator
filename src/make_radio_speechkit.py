def synth(text, voice, emotion, speed, out):
    data = urllib.parse.urlencode({"text": text, "lang": "ru-RU", "voice": voice,
                                   "emotion": emotion, "speed": speed, "format": "mp3"}).encode()
    req = urllib.request.Request("https://tts.api.cloud.yandex.net/speech/v1/tts:synthesize",
                                 data=data, headers={"Authorization": f"Api-Key {KEY}"})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                body = r.read()
            if len(body) > 500:
                open(out, "wb").write(body); return
        except urllib.error.HTTPError as e:
            msg = e.read()[:300]
            if b"Unsupported voice" in msg and voice != "filipp":
                print(f"voice {voice} unsupported -> filipp"); voice = "filipp"; emotion="neutral"
                data = urllib.parse.urlencode({"text": text, "lang": "ru-RU", "voice": voice,
                                   "emotion": emotion, "speed": speed, "format": "mp3"}).encode()
                req = urllib.request.Request(req.full_url, data=data, headers=req.headers); continue
            if attempt == 2:
                print(f"HTTP {e.code} on '{text[:40]}' voice={voice}: {msg}"); sys.exit(1)
        time.sleep(1)

def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print("FAIL:", " ".join(cmd[:3]), r.stderr[-300:]); sys.exit(1)

