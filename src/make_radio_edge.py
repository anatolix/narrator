def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print("FAIL:", " ".join(cmd[:4]), r.stderr[-300:])
        sys.exit(1)

async def synth(text, voice, pitch, rate, out):
    c = edge_tts.Communicate(text, voice, pitch=pitch, rate=rate)
    await c.save(out)

async def main():
    parts = []
    for i, (role, text) in enumerate(SEG):
        voice, pitch, rate = CAST[role]
        out = f"seg2-{i:03d}.mp3"
        for attempt in range(3):
            try:
                await synth(text, voice, pitch, rate, out)
                if os.path.getsize(out) > 500:
                    break
            except Exception as e:
                if attempt == 2:
                    print(f"TTS FAIL seg {i} ({role}): {e}")
                    sys.exit(1)
                await asyncio.sleep(1)
        parts.append(out)
        if i % 20 == 0:
            print(f"...{i}/{len(SEG)}", flush=True)

    r = subprocess.run(["ffprobe","-v","error","-select_streams","a:0",
                        "-show_entries","stream=sample_rate","-of","csv=p=0",parts[0]],
                       capture_output=True, text=True)
    sr = r.stdout.strip() or "24000"
    run(["ffmpeg","-y","-f","lavfi","-i",f"anullsrc=r={sr}:cl=mono","-t","0.45",
         "-q:a","2","sil2.mp3"])

    with open("list2.txt","w") as f:
        for i,p in enumerate(parts):
            f.write(f"file '{p}'\n")
            if i < len(parts)-1:
                f.write("file 'sil2.mp3'\n")

    run(["ffmpeg","-y","-f","concat","-safe","0","-i","list2.txt","-c:a","libmp3lame",
         "-q:a","2","/workspace/art/REMOVED-v2.mp3"])
    print("DONE")

asyncio.run(main())
